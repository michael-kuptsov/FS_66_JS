// HTTP (Hypertext Transfer Protocol) - это протокол передачи данных, который используется для обмена информацией между клиентом и сервером в сети Интернет. HTTP определяет правила и форматы для запросов и ответов, обеспечивая взаимодействие между веб-браузерами и веб-серверами.
//Response and Request - это объекты, которые представляют собой запросы и ответы в протоколе HTTP. Request содержит информацию о запросе, отправленном клиентом на сервер, включая URL, метод, заголовки и тело запроса. Response содержит информацию о ответе сервера на запрос, включая статусный код, заголовки и тело ответа. Эти объекты используются для обмена данными между клиентом и сервером в веб-приложениях.Похоже на СМС переписку, где Request - это сообщение, отправленное пользователем, а Response - это ответ на это сообщение от получателя.
//Структура запроса и ответа в HTTP включает в себя следующие элементы:
// 1. Request (Запрос):
// - Метод (Method): Определяет действие, которое клиент хочет выполнить (например, GET, POST, PUT, DELETE).
// - URL (Uniform Resource Locator): Адрес ресурса, к которому клиент обращается.
// - Заголовки (Headers): Дополнительная информация о запросе, такая как тип контента, авторизация и т.д.
// - Тело запроса (Body): Данные, отправляемые на сервер (используется в методах POST и PUT).

// 2. Response (Ответ):
// - Статусный код (Status Code): Числовой код, указывающий результат обработки запроса (например, 200 OK, 404 Not Found).
// - Заголовки (Headers): Дополнительная информация о ответе, такая как тип контента, длина ответа и т.д.
// - Тело ответа (Body): Данные, возвращаемые сервером в ответ на запрос (например, HTML, JSON, изображения и т.д.).

// Взаимодействие между клиентом и сервером происходит следующим образом:
// 1. Клиент отправляет Request на сервер с указанием метода, URL, заголовков и тела запроса (если необходимо).
// 2. Сервер обрабатывает запрос и формирует Response с соответствующим статусным кодом, заголовками и телом ответа.
// 3. Клиент получает Response и обрабатывает его в соответствии с полученными данными.
//REST (Representational State Transfer) - это архитектурный стиль взаимодействия между клиентом и сервером в веб-приложениях. REST использует стандартные HTTP-методы (GET, POST, PUT, DELETE) для выполнения операций над ресурсами, которые представляют собой данные или объекты. RESTful API обеспечивает простоту, масштабируемость и гибкость при обмене данными между клиентом и сервером.
//GET Чтение данных с сервера. Используется для получения информации о ресурсах.
//POST Создание нового ресурса на сервере. Используется для отправки данных на сервер и создания новых объектов.
//PUT Обновление существующего ресурса на сервере. Используется для изменения данных существующих объектов.
//DELETE Удаление ресурса с сервера. Используется для удаления объектов с сервера.
//fetch and Axios - это два популярных способа выполнения HTTP-запросов в JavaScript. fetch - это встроенная функция в браузерах, которая позволяет отправлять запросы и получать ответы. Она возвращает промис, который можно использовать для обработки результатов. Axios - это сторонняя библиотека, которая предоставляет более удобный и мощный интерфейс для работы с HTTP-запросами. Она поддерживает промисы, имеет встроенную обработку ошибок и упрощает работу с заголовками и данными.


